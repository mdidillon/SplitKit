#!/bin/bash
# Fetches the Spike B glTF corpus (spec §10) from KhronosGroup/glTF-Sample-Assets into Fixtures/
# and regenerates Fixtures/LICENSES.md from each model's metadata.json.
#
# Usage: ./scripts/fetch-corpus.sh            (skips files that already exist)
#        FORCE=1 ./scripts/fetch-corpus.sh    (re-downloads everything)
#
# Required models must download or the script exits non-zero. Optional models (KHR extension
# probes) are skipped with a warning if missing upstream.
set -euo pipefail

BASE="https://raw.githubusercontent.com/KhronosGroup/glTF-Sample-Assets/main/Models"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FIX="$ROOT/Fixtures"
REFDIR="$ROOT/../../Docs/ADR/assets/spikeB/reference"
LICENSES="$FIX/LICENSES.md"
FORCE="${FORCE:-0}"

mkdir -p "$FIX" "$REFDIR"

download() { # url dest
    local url="$1" dest="$2"
    if [[ -s "$dest" && "$FORCE" != "1" ]]; then
        return 0
    fi
    mkdir -p "$(dirname "$dest")"
    curl -sfL --retry 3 -o "$dest.part" "$url" || { rm -f "$dest.part"; return 1; }
    mv "$dest.part" "$dest"
}

# json_list file keyPrefix field -> prints values of keyPrefix.N.field for N = 0.. (stops at first miss)
json_list() {
    local file="$1" prefix="$2" field="$3" i=0 v
    while v="$(plutil -extract "$prefix.$i.$field" raw -o - "$file" 2>/dev/null)"; do
        printf '%s\n' "$v"
        i=$((i + 1))
    done
}

json_value() { plutil -extract "$2" raw -o - "$1" 2>/dev/null || true; }

LICENSE_ROWS=""

fetch_model() { # name variant file required|optional [copyReference]
    local name="$1" variant="$2" file="$3" need="$4" copyref="${5:-no}"
    local dir="$FIX/$name/$variant"
    echo "==> $name/$variant/$file ($need)"
    if ! download "$BASE/$name/$variant/$file" "$dir/$file"; then
        if [[ "$need" == "required" ]]; then
            echo "ERROR: required model $name/$variant/$file failed to download" >&2
            exit 1
        fi
        echo "WARN: optional model $name/$variant/$file not available, skipped" >&2
        return 0
    fi
    if [[ "$file" == *.gltf ]]; then
        local uri
        while IFS= read -r uri; do
            [[ -z "$uri" || "$uri" == data:* ]] && continue
            download "$BASE/$name/$variant/$uri" "$dir/$uri" || {
                echo "ERROR: dependency $uri of $name failed to download" >&2; exit 1; }
        done < <(json_list "$dir/$file" buffers uri; json_list "$dir/$file" images uri)
    fi

    local meta="$FIX/$name/metadata.json"
    download "$BASE/$name/metadata.json" "$meta" || { echo "ERROR: metadata.json for $name missing" >&2; exit 1; }
    local license artist owner year licenseUrl shot
    license="$(json_value "$meta" legal.0.license)"
    artist="$(json_value "$meta" legal.0.artist)"
    owner="$(json_value "$meta" legal.0.owner)"
    year="$(json_value "$meta" legal.0.year)"
    licenseUrl="$(json_value "$meta" legal.0.licenseUrl)"
    # Some metadata.json files use repo-relative licence links (e.g. SCEA); make them absolute.
    licenseUrl="${licenseUrl/#..\/..\//https://github.com/KhronosGroup/glTF-Sample-Assets/blob/main/}"
    shot="$(json_value "$meta" screenshot)"
    if [[ -n "$shot" ]]; then
        download "$BASE/$name/$shot" "$FIX/$name/$shot" || echo "WARN: screenshot for $name missing" >&2
        if [[ "$copyref" == "ref" && -s "$FIX/$name/$shot" ]]; then
            cp "$FIX/$name/$shot" "$REFDIR/$name-reference.${shot##*.}"
        fi
    fi
    LICENSE_ROWS+="| $name | $variant/$file | $need | ${license:-unknown} | ${artist:-?} | ${owner:-?} | ${year:-?} | ${licenseUrl:-} |"$'\n'
}

# Required rows (§10): meshes/hierarchy, PBR, external .bin/textures, embedded GLB.
fetch_model Box             glTF         Box.gltf             required
fetch_model BoxTextured     glTF         BoxTextured.gltf     required ref
fetch_model Duck            glTF-Binary  Duck.glb             required ref
fetch_model DamagedHelmet   glTF-Binary  DamagedHelmet.glb    required ref
fetch_model CesiumMilkTruck glTF         CesiumMilkTruck.gltf required ref
# Optional rows (§10): skinning/animation, morph targets.
fetch_model CesiumMan          glTF-Binary CesiumMan.glb          optional
fetch_model RiggedSimple       glTF-Binary RiggedSimple.glb       optional
fetch_model AnimatedMorphCube  glTF-Binary AnimatedMorphCube.glb  optional
# Optional KHR extension probes.
fetch_model TransmissionTest   glTF-Binary TransmissionTest.glb   optional
fetch_model ClearCoatTest      glTF-Binary ClearCoatTest.glb      optional
fetch_model Box                glTF-Draco  Box.gltf               optional
fetch_model Duck               glTF-Draco  Duck.gltf              optional

{
    echo "# Spike B fixture licences"
    echo
    echo "Generated by \`scripts/fetch-corpus.sh\` from each model's \`metadata.json\` in"
    echo "[KhronosGroup/glTF-Sample-Assets](https://github.com/KhronosGroup/glTF-Sample-Assets) (branch \`main\`)."
    echo "Reference screenshots copied to \`Docs/ADR/assets/spikeB/reference/\` carry the same licence as their model."
    echo "Hand-made error fixtures under \`Errors/\` are original to this repo (MIT)."
    echo
    echo "| Model | File | Row | Licence | Artist | Owner | Year | Licence URL |"
    echo "|---|---|---|---|---|---|---|---|"
    printf '%s' "$LICENSE_ROWS"
} > "$LICENSES"

echo "Corpus ready in $FIX"
du -sh "$FIX"
